# Numeric
# integer
a = 3270 
print("ini tipe data integer (int) : {0}".format(a))
# float
b = 3.14
print("ini tipe data float (float) {0}".format(b))
# kompleks
c = 2 + 3j
print("ini tipe data komplex (komplex) {0}".format(c))

# squensial
# list
d = [1,2,3,4]
print("ini tipe data list (list) {0}".format(d))
# truplet
f = (5,6,7,8)
print("ini tipe data truplet (truplet) {0}".format(f))
# range
# range(start,end,step)
e = range(10)
print("ini tipe data range (range) {0}".format(e))

# text
# char / varchar
g = 'A'
print("ini tipe data char (char) {0}".format(g))
# string
h = "Alfadjri Dwi Fadhilah"
print("ini tipe data String (str) {0}".format(h))

# map
# dictionary (dic)
profile = { "nama" : "alfadjri" , "usia" : 25}
print("ini tipe data dictionary (dict) {0}".format(profile))

# set type
# set
i = {1,2,3,4}
print("ini tipe data settype (set) {0}".format(i))
# forzenset
j = frozenset({5,6,7,8})
print("ini tipe data frozenset (frozenset) {0}".format(j))

# boolean
# bernilai True (1) or False (0)
kondisi = True
print("ini tipe data boolean (bool) {0}".format(kondisi))