x = 3
y = 2

# Penjumlahan (+)
hasil = x + y 
print(f"Hasil dari {x} + {y} = {hasil}")
# Pengunrangan
hasil = x - y 
print(f"Hasil dari {x} - {y} = {hasil}")
# Perkalian (*)
hasil = x * y 
print(f"Hasil dari {x} x {y} = {hasil}")
# Pembagian nilainya float
hasil = x / y 
print(f"Hasil dari {x} : {y} = {hasil}")
# Pembagian nilainya Intenger
hasil = x // y 
print(f"Hasil dari {x} : {y} = {hasil}")
# sisa pembagian (modulus %)
hasil = x % y
print(f"Hasil dari {x} % {y} = {hasil}")
# Pangkat (**)
hasil = x ** y
print(f"Hasil dari {x} ^ {y} = {hasil}")

#hasil = hasil + 1
# incerment (++) (+= 1)
hasil += 1
print(f"Hasil : {hasil}")
# Decermnet (--) (-= 1)
hasil -= 10
print(f"Hasil : {hasil}")

