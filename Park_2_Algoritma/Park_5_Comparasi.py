x = 2
y = 2

# Besar dari (>)
hasil = x > y 
print(f"Apakah {x} Besar dari (>) {y} adalah {hasil}")
# Besar dari sama dengan (>=)
hasil = x >= y
print(f"Apakah {x} Besar dari sama dengan (>=) {y} adalah {hasil}")
# Kecil dari (<)
hasil = x < y 
print(f"Apakah {x} Kecil dari (<) {y} adalah {hasil}")
# Kecil dari sama dengan (<=)
hasil = x <= y
print(f"Apakah {x} Kecil dari sama dengan (<=) {y} adalah {hasil}")

x = 2
y = "2"
# Sama dengan 
hasil = x == y 
print(f"Apakah {x} sama dengan {y} adalah {hasil}")
# Tidak sama dengan Not (!)
hasil = x != y
print(f"Apakah {x} tidak sama dengan != {y} adalah {hasil}")
